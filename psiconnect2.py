"""Spectrum plot: mean across channels, canonical bands shaded"""

def plot_spectrum_with_bands(dfa_spec_pre, dfa_spec_post, fei_spec_pre, fei_spec_post,
                               bin_centers, canonical_bands):
    fig, axes = plt.subplots(2, 1, figsize=(12, 9), sharex=True)

    band_colors = {
        "delta": "#B3CDE3", "theta": "#CCEBC5", "alpha": "#DECBE4",
        "beta": "#FED9A6", "gamma": "#FFFFCC",
    }

    for ax, spec_pre, spec_post, metric_name, ylabel in [
        (axes[0], dfa_spec_pre, dfa_spec_post, "DFA", "DFA exponent α"),
        (axes[1], fei_spec_pre, fei_spec_post, "fE/I", "fE/I"),
    ]:
        mean_pre = np.nanmean(spec_pre, axis=0)
        sem_pre = np.nanstd(spec_pre, axis=0) / np.sqrt(spec_pre.shape[0])
        mean_post = np.nanmean(spec_post, axis=0)
        sem_post = np.nanstd(spec_post, axis=0) / np.sqrt(spec_post.shape[0])

        for band_name, (lo, hi) in canonical_bands.items():
            ax.axvspan(lo, hi, color=band_colors.get(band_name, "#EEEEEE"), alpha=0.3, zorder=0)

        ax.plot(bin_centers, mean_pre, "-o", color="tab:blue", label="Pre", markersize=3)
        ax.fill_between(bin_centers, mean_pre - sem_pre, mean_pre + sem_pre, color="tab:blue", alpha=0.2)

        ax.plot(bin_centers, mean_post, "-o", color="tab:red", label="Post", markersize=3)
        ax.fill_between(bin_centers, mean_post - sem_post, mean_post + sem_post, color="tab:red", alpha=0.2)

        ax.set_ylabel(ylabel)
        ax.set_title(f"{metric_name} — Frequency-Resolved Spectrum (mean ± SEM across channels)")
        ax.legend()
        ax.grid(alpha=0.3)

    axes[-1].set_xlabel("Frequency (Hz)")
    fig.suptitle(f"Subject {SUBJECT} — Pre vs Post Psilocybin — Frequency-Resolved DFA & fE/I",
                 fontsize=14, fontweight="bold")
    fig.tight_layout()
    return fig

