"""Load and parse .mat files"""

def load_ft_mat(fpath):
    mat = sio.loadmat(fpath, squeeze_me=True, struct_as_record=False)
    ftData = mat["ftData"]

    fs = int(round(float(ftData.fsample)))   # crosci requires an int sampling rate
    chnames = list(ftData.label)
    signal = np.asarray(ftData.trial, dtype=float)   # (n_channels, n_times)
    if signal.dtype == object:
        signal = np.asarray(signal.item(), dtype=float)

    return signal, fs, chnames

"""Compute DFA and fE/I per band"""

def compute_metrics_allbands(fpath, bands=ALL_BANDS):
    signal, fs, chnames = load_ft_mat(fpath)
    n_channels, n_times = signal.shape
    print(f"  {n_channels} channels, {n_times} samples, fs={fs} Hz, "
          f"duration={n_times/fs:.1f}s")

    dfa_by_band = {}
    fei_by_band = {}

    for band_name, band_range in bands.items():
        print(f"    Band: {band_name} ({band_range[0]}-{band_range[1]} Hz)")
        try:
            band_biomarkers = compute_band_biomarkers(signal, fs, band_range)
            dfa_by_band[band_name] = np.atleast_1d(np.asarray(band_biomarkers["DFA"], dtype=float))
            fei_by_band[band_name] = np.atleast_1d(np.asarray(band_biomarkers["fEI"], dtype=float))
        except (IndexError, ValueError) as e:
            print(f"    WARNING: {band_name} ({band_range}) failed — {e}")
            print(f"    Filling with NaN for this band. Consider adjusting its range.")
            dfa_by_band[band_name] = np.full(n_channels, np.nan)
            fei_by_band[band_name] = np.full(n_channels, np.nan)

    return {
        "chnames": chnames,
        "fs": fs,
        "dfa": dfa_by_band,
        "fei": fei_by_band,
    }

