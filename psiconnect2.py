"""Topomap grid: per-band, pre vs post vs difference"""

def plot_metric_grid(metric_key, metric_label, cbar_label):
    n_bands = len(BAND_NAMES)
    fig, axes = plt.subplots(n_bands, 3, figsize=(12, 3.2 * n_bands))

    for row, band_name in enumerate(BAND_NAMES):
        v_pre = np.nan_to_num(results["pre"][metric_key][band_name],
                               nan=np.nanmean(results["pre"][metric_key][band_name]))
        v_post = np.nan_to_num(results["post"][metric_key][band_name],
                                nan=np.nanmean(results["post"][metric_key][band_name]))
        diff = v_post - v_pre

        vmin = min(v_pre.min(), v_post.min())
        vmax = max(v_pre.max(), v_post.max())
        vabs = np.max(np.abs(diff)) if np.any(np.isfinite(diff)) else 1

        ax = axes[row, 0]
        im1, _ = mne.viz.plot_topomap(v_pre, info, axes=ax, show=False,
                                       cmap=cmap_becp, vlim=(vmin, vmax))
        ax.set_ylabel(band_name, fontsize=11, fontweight="bold")
        if row == 0:
            ax.set_title("Pre", fontsize=12, fontweight="bold")
        fig.colorbar(im1, ax=ax, shrink=0.7, pad=0.03)

        ax = axes[row, 1]
        im2, _ = mne.viz.plot_topomap(v_post, info, axes=ax, show=False,
                                       cmap=cmap_becp, vlim=(vmin, vmax))
        if row == 0:
            ax.set_title("Post", fontsize=12, fontweight="bold")
        fig.colorbar(im2, ax=ax, shrink=0.7, pad=0.03)

        ax = axes[row, 2]
        im3, _ = mne.viz.plot_topomap(diff, info, axes=ax, show=False,
                                       cmap="RdBu_r", vlim=(-vabs, vabs))
        if row == 0:
            ax.set_title("Δ (Post − Pre)", fontsize=12, fontweight="bold")
        fig.colorbar(im3, ax=ax, shrink=0.7, pad=0.03)

        axes[row, 0].annotate(band_name.upper(), xy=(-0.25, 0.5),
                               xycoords="axes fraction", fontsize=11,
                               fontweight="bold", rotation=90, va="center", ha="center")

    fig.suptitle(f"Subject {SUBJECT} — {metric_label} — All Bands (Pre / Post / Difference)",
                 fontsize=15, fontweight="bold", y=1.0)
    fig.tight_layout()
    return fig

