def get_files(tree=None):
    resp = requests.post(
        "https://openneuro.org/crn/graphql",
        json={"query": query, "variables": {"datasetId": dataset, "tag": version, "tree": tree}},
    )
    data = resp.json()
    if "errors" in data:
        print("ERROR:", data["errors"])
        return []
    return data["data"]["snapshot"]["files"]

