"""Channel × band heatmap"""

def plot_channel_band_heatmap(metric_key, metric_label, cbar_label, cmap="RdBu_r"):
    diff_matrix = np.zeros((n_channels, len(BAND_NAMES)))
    for col, band_name in enumerate(BAND_NAMES):
        v_pre = np.nan_to_num(results["pre"][metric_key][band_name],
                               nan=np.nanmean(results["pre"][metric_key][band_name]))
        v_post = np.nan_to_num(results["post"][metric_key][band_name],
                                nan=np.nanmean(results["post"][metric_key][band_name]))
        diff_matrix[:, col] = v_post - v_pre

    vabs = np.nanmax(np.abs(diff_matrix))

    fig, ax = plt.subplots(figsize=(1.4 * len(BAND_NAMES) + 2, 0.22 * n_channels + 2))
    im = ax.imshow(diff_matrix, cmap=cmap, vmin=-vabs, vmax=vabs, aspect="auto")

    ax.set_xticks(range(len(BAND_NAMES)))
    ax.set_xticklabels(BAND_NAMES, rotation=45, ha="right")
    ax.set_yticks(range(n_channels))
    ax.set_yticklabels(chnames, fontsize=7)
    ax.set_xlabel("Frequency band")
    ax.set_ylabel("Channel")
    ax.set_title(f"{metric_label} — Δ (Post − Pre), All Channels × All Bands", fontweight="bold")

    fig.colorbar(im, ax=ax, shrink=0.8, label=cbar_label)
    fig.tight_layout()
    return fig, diff_matrix

