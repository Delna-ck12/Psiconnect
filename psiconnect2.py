"""Fine-grained frequency-resolved spectrum"""

def compute_spectrum_for_session(fpath, spectrum_range=SPECTRUM_RANGE):
    signal, fs, chnames = load_ft_mat(fpath)
    spectrum_biomarkers = compute_spectrum_biomarkers(signal, fs, spectrum_range)
    dfa_spec = np.atleast_2d(np.asarray(spectrum_biomarkers["DFA"], dtype=float))   # (n_channels, n_bins)
    fei_spec = np.atleast_2d(np.asarray(spectrum_biomarkers["fEI"], dtype=float))   # (n_channels, n_bins)
    return dfa_spec, fei_spec, chnames, fs

